package BASICS;

public class DATA_TYPES {
    static void main(String[] args) {
        int a = 67;
        int b = 7;
        System.out.println(a / b);

        float c = 67;
        float d = 7;
        System.out.println(c / d);

        double e = 67;
        double f = 7;
        System.out.println(e / f);

        char g = 'b';
        String s = "YAYY";
        System.out.println(g);
        System.out.println(s);

    }
}
