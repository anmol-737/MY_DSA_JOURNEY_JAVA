package BASICS;

public class variables_basics {
    static void main(String[] args) {
        int b ; // variable declaration
        b = 10; // variable initialization
        int a = 20 ; //declaration and initialization ek sath
        System.out.println(b);
        System.out.println(b+a);
        int x = 73; /*we can declare variable only once but its value can be updated any number of times*/
        System.out.println(x);
        x = 100; // there would  be an error if I would've written int again
        System.out.println(x);
        x= x+10;
        System.out.println(x);
        x= x-20;
        System.out.println(x);
        x= x*10;
        System.out.println(x);
        x= x/10;
        System.out.println(x);
        x= x%7; // to find remainder
        System.out.println(x);






    }
}
