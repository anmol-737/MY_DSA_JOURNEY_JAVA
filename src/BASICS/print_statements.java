package BASICS;

public class print_statements {
    static void main() {
         //different types of print statements
         System.out.print("Hello"); //normally prints the thing present in parentheses NEXT THING WILL BE PRINTED IN SAME LINE
         System.out.println("HI"); // coz of "LN" used as end of statement enter key is pressed AFTER the content is printed
         System.out.print("Welcome"); //normally prints the thing present in parentheses but in next line coz "ln" WAS USED IN PREVIOUS STATEMENT
         System.out.print("\nto my DSA journey"); /* "\n is an escape sequence used to move to next line", here it's used in front to press the enter key
         BEFORE printing of the content in brackets */
         System.out.print(" using java\n");/* here "\n" is  used in last to press the enter key AFTER printing of the content in brackets */
         System.out.print("LET'S BEGIN ");
         System.out.println("\n I am Anmol \n future multi billionaire \n ^_^ ");
     }
 }