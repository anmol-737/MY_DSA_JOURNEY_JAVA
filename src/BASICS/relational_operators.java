package BASICS;

public class relational_operators {
    static void main(String[] args) {
        System.out.println(5>3);

        System.out.println(5<3);

        System.out.println(5!=3);

        System.out.println(8>=7);

        System.out.println(8<=7);

        System.out.println(7==7);

        System.out.println(7==9);
    }
}
