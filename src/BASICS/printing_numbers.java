package BASICS;

public class printing_numbers {
    static void main(String[] args) {
        System.out.println(10+2);//printing a number (do not put number in "" else it would be treated as text)
        System.out.println("10+2");// treated as string(text)
        System.out.print(5); /* printing numbers together*/
        System.out.println(20);

        System.out.print(10 + " "); // adding space between numbers but printing in same line
        System.out.println(5);

    }
}
