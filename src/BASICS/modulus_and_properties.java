package BASICS;

public class modulus_and_properties {
    static void main(String[] args) {

        System.out.println(2%5); //a%b = a if a <b

        System.out.println(39%10); // a%b will give us remainder when a is divided by b

        System.out.println((-39)%10); // (-a)%b  = -(a%b)


        System.out.println(39%(-10)); // a%(-b) = a%b


        System.out.println((-39)%(-10));
    }
}
